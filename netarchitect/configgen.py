"""
configgen.py — Device configuration generator for NetArchitect.

generate_configs(preset_name, topology) → dict[device_name, config_str]

Rules enforced:
  - NEVER use "switchport trunk allowed vlan all"
  - Always use wildcard masks in OSPF network statements
  - Explicit VLAN lists on every trunk port
  - rapid-pvst on campus switches
"""

from __future__ import annotations
from typing import Dict


# ── Shared helpers ─────────────────────────────────────────────────────────────

def _header(device: str, preset: str, description: str) -> str:
    return (
        f"! ========================================================\n"
        f"! Device  : {device}\n"
        f"! Preset  : {preset}\n"
        f"! Purpose : {description}\n"
        f"! Generated by NetArchitect — explicit VLAN lists required on all trunks\n"
        f"! ========================================================\n"
        f"!\n"
    )


# ── CAMPUS preset ──────────────────────────────────────────────────────────────

def _campus_core_switch() -> str:
    """
    Core distribution switch configuration for a 3-building campus.

    VLANs: 10 (Staff), 20 (Students), 30 (IoT), 99 (Native/Mgmt)
    Trunks: explicit allowed-vlan list — never 'allowed vlan all'
    STP  : rapid-pvst (IEEE 802.1w)
    SVIs : one per VLAN for inter-VLAN routing
    OSPF : network statements use wildcard masks
    """
    return """\
hostname CORE-SW01
!
! ── Global STP ─────────────────────────────────────────────────────────────
spanning-tree mode rapid-pvst
spanning-tree extend system-id
spanning-tree vlan 10,20,30,99 priority 4096
!
! ── VLAN Database ──────────────────────────────────────────────────────────
vlan 10
 name Staff
vlan 20
 name Students
vlan 30
 name IoT
vlan 99
 name Mgmt-Native
!
! ── Uplink trunk to Access-SW01 (Building A, 80 m — Cat6a UTP / 10GBASE-T) ─
interface GigabitEthernet1/0/1
 description Trunk-to-ACCESS-SW01-BuildingA
 switchport mode trunk
 switchport trunk native vlan 99
 switchport trunk allowed vlan 10,20,30
 spanning-tree link-type point-to-point
 no shutdown
!
! ── Uplink trunk to Access-SW02 (Building B, 250 m — OM4 MMF / 10GBASE-SR) ─
interface GigabitEthernet1/0/2
 description Trunk-to-ACCESS-SW02-BuildingB
 switchport mode trunk
 switchport trunk native vlan 99
 switchport trunk allowed vlan 10,20,30
 spanning-tree link-type point-to-point
 no shutdown
!
! ── Uplink trunk to Access-SW03 (Building C, 380 m — OM4 MMF / 10GBASE-SR) ─
interface GigabitEthernet1/0/3
 description Trunk-to-ACCESS-SW03-BuildingC
 switchport mode trunk
 switchport trunk native vlan 99
 switchport trunk allowed vlan 10,20,30
 spanning-tree link-type point-to-point
 no shutdown
!
! ── SVIs for inter-VLAN routing ─────────────────────────────────────────────
interface Vlan10
 description Staff-Gateway
 ip address 10.0.0.1 255.255.254.0
 ip ospf 1 area 0
 no shutdown
!
interface Vlan20
 description Students-Gateway
 ip address 10.0.4.1 255.255.252.0
 ip ospf 1 area 0
 no shutdown
!
interface Vlan30
 description IoT-Gateway
 ip address 10.0.8.1 255.255.255.0
 ip ospf 1 area 0
 no shutdown
!
interface Vlan99
 description Mgmt-Gateway
 ip address 10.0.9.1 255.255.255.192
 ip ospf 1 area 0
 no shutdown
!
! ── OSPF — wildcard masks (NOT subnet masks) in network statements ──────────
router ospf 1
 router-id 10.0.9.1
 passive-interface default
 no passive-interface Vlan10
 no passive-interface Vlan20
 no passive-interface Vlan30
 no passive-interface Vlan99
 ! network <ip> <wildcard> area <id>
 network 10.0.0.0 0.0.1.255 area 0
 network 10.0.4.0 0.0.3.255 area 0
 network 10.0.8.0 0.0.0.255 area 0
 network 10.0.9.0 0.0.0.63  area 0
!
! ── Management ───────────────────────────────────────────────────────────────
ip default-gateway 10.0.9.1
service password-encryption
no ip http server
logging buffered 16384 warnings
!
end
"""


def _campus_access_switch(sw_num: int, building: str, distance_m: int, medium: str) -> str:
    """Generate a campus access-switch config (sw_num = 1 or 2)."""
    hostname = f"ACCESS-SW0{sw_num}"
    uplink_desc = f"Uplink-to-CORE-SW01 ({distance_m} m — {medium})"
    svi_ip = f"10.0.9.{10 + sw_num}"

    return f"""\
hostname {hostname}
!
! ── Global STP ─────────────────────────────────────────────────────────────
spanning-tree mode rapid-pvst
spanning-tree extend system-id
spanning-tree vlan 10,20,30,99 priority 8192
!
! ── VLAN Database ──────────────────────────────────────────────────────────
vlan 10
 name Staff
vlan 20
 name Students
vlan 30
 name IoT
vlan 99
 name Mgmt-Native
!
! ── Uplink trunk to Core ───────────────────────────────────────────────────
interface GigabitEthernet0/1
 description {uplink_desc}
 switchport mode trunk
 switchport trunk native vlan 99
 switchport trunk allowed vlan 10,20,30
 spanning-tree link-type point-to-point
 no shutdown
!
! ── Access ports (staff) ───────────────────────────────────────────────────
interface range GigabitEthernet0/2 - 12
 description Staff-Access-Port
 switchport mode access
 switchport access vlan 10
 spanning-tree portfast
 spanning-tree bpduguard enable
 no shutdown
!
! ── Access ports (students) ────────────────────────────────────────────────
interface range GigabitEthernet0/13 - 22
 description Student-Access-Port
 switchport mode access
 switchport access vlan 20
 spanning-tree portfast
 spanning-tree bpduguard enable
 no shutdown
!
! ── Mgmt SVI ───────────────────────────────────────────────────────────────
interface Vlan99
 description Mgmt
 ip address {svi_ip} 255.255.255.192
 no shutdown
!
ip default-gateway 10.0.9.1
service password-encryption
!
end
"""


def _generate_campus(topology: dict) -> Dict[str, str]:
    configs = {}
    configs["CORE-SW01"] = _header("CORE-SW01", "campus", "Core distribution switch") + _campus_core_switch()
    configs["ACCESS-SW01"] = (
        _header("ACCESS-SW01", "campus", "Access switch — Building A")
        + _campus_access_switch(1, "Building-A", 80, "Cat6a UTP / 10GBASE-T")
    )
    configs["ACCESS-SW02"] = (
        _header("ACCESS-SW02", "campus", "Access switch — Building B")
        + _campus_access_switch(2, "Building-B", 250, "OM4 MMF / 10GBASE-SR")
    )
    return configs


# ── METRO preset ───────────────────────────────────────────────────────────────

def _metro_hq_router() -> str:
    return """\
hostname HQ-RTR01
!
! ── Interfaces ──────────────────────────────────────────────────────────────
interface GigabitEthernet0/0
 description HQ-LAN
 ip address 172.16.0.1 255.255.255.0
 ip ospf 1 area 0
 no shutdown
!
! ── WAN link to Site1 (15 000 m — OS2 SMF / 10GBASE-LR, 1310 nm) ───────────
! Optical budget: Tx=+0.5 dBm, Rx=-14.4 dBm, budget=14.9 dB
! Link loss: 15 km × 0.4 dB/km + 2×0.5 dB = 7.0 dB, margin=7.9 dB OK
interface GigabitEthernet0/1
 description WAN-to-SITE1-RTR01 OS2-SMF-10GBASE-LR
 ip address 172.16.14.1 255.255.255.252
 ip ospf 1 area 0
 no shutdown
!
! ── WAN link to Site2 (35 000 m — OS2 SMF / 10GBASE-ER, 1550 nm) ───────────
! Optical budget: Tx=+0.5 dBm, Rx=-15.8 dBm, budget=16.3 dB
! Link loss: 35 km × 0.4 dB/km + 2×0.5 dB = 15.0 dB, margin=1.3 dB OK
interface GigabitEthernet0/2
 description WAN-to-SITE2-RTR01 OS2-SMF-10GBASE-ER
 ip address 172.16.14.5 255.255.255.252
 ip ospf 1 area 0
 no shutdown
!
! ── OSPF — wildcard masks in network statements ─────────────────────────────
router ospf 1
 router-id 172.16.0.1
 area 1 stub
 network 172.16.0.0 0.0.0.255 area 0
 network 172.16.14.0 0.0.0.3 area 0
 network 172.16.14.4 0.0.0.3 area 0
!
! ── QoS — class-based queuing for sub-5ms latency SLA ──────────────────────
class-map match-all VOICE
 match dscp ef
class-map match-all VIDEO
 match dscp af41
class-map match-all CRITICAL-DATA
 match dscp af31
!
policy-map WAN-EGRESS-QOS
 class VOICE
  priority percent 20
 class VIDEO
  bandwidth percent 30
 class CRITICAL-DATA
  bandwidth percent 25
 class class-default
  fair-queue
!
interface GigabitEthernet0/1
 service-policy output WAN-EGRESS-QOS
interface GigabitEthernet0/2
 service-policy output WAN-EGRESS-QOS
!
end
"""


def _metro_site_router(site_num: int, distance_m: int, transceiver: str,
                       lan_net: str, wan_ip: str) -> str:
    hostname = f"SITE{site_num}-RTR01"
    return f"""\
hostname {hostname}
!
! ── LAN interface ───────────────────────────────────────────────────────────
interface GigabitEthernet0/0
 description Site{site_num}-LAN
 ip address {lan_net} 255.255.255.0
 ip ospf 1 area {site_num}
 no shutdown
!
! ── WAN uplink to HQ ({distance_m} m — OS2 SMF / {transceiver}) ────────────
interface GigabitEthernet0/1
 description WAN-to-HQ-RTR01 OS2-SMF-{transceiver}
 ip address {wan_ip} 255.255.255.252
 ip ospf 1 area 0
 no shutdown
!
! ── OSPF multi-area — wildcard masks ────────────────────────────────────────
router ospf 1
 router-id {lan_net}
 area {site_num} stub
 network {lan_net} 0.0.0.255 area {site_num}
 network {wan_ip} 0.0.0.3 area 0
!
! ── QoS outbound ────────────────────────────────────────────────────────────
policy-map WAN-EGRESS-QOS
 class VOICE
  priority percent 20
 class class-default
  fair-queue
!
interface GigabitEthernet0/1
 service-policy output WAN-EGRESS-QOS
!
end
"""


def _generate_metro(topology: dict) -> Dict[str, str]:
    configs = {}
    configs["HQ-RTR01"] = _header("HQ-RTR01", "metro", "HQ router — MAN hub") + _metro_hq_router()
    configs["SITE1-RTR01"] = (
        _header("SITE1-RTR01", "metro", "Remote site 1 router")
        + _metro_site_router(1, 15000, "10GBASE-LR", "172.16.1.1", "172.16.14.2")
    )
    configs["SITE2-RTR01"] = (
        _header("SITE2-RTR01", "metro", "Remote site 2 router")
        + _metro_site_router(2, 35000, "10GBASE-ER", "172.16.2.1", "172.16.14.6")
    )
    return configs


# ── WAN preset ─────────────────────────────────────────────────────────────────

def _wan_site_router(city: str, asn: int, loopback: str,
                     lan_net: str, bgp_neighbors: list) -> str:
    """
    Generate a WAN site router config with multi-area OSPF + eBGP + IKEv2/IPsec.
    bgp_neighbors: list of (neighbor_ip, remote_asn, description)
    """
    bgp_neighbor_stanzas = "\n".join(
        f" neighbor {ip} remote-as {asn_r}\n"
        f" neighbor {ip} description {desc}\n"
        f" neighbor {ip} send-community\n"
        f" neighbor {ip} route-map RM-OUT-{city.upper()} out"
        for ip, asn_r, desc in bgp_neighbors
    )

    return f"""\
hostname {city}-RTR01
!
! ── Loopback ────────────────────────────────────────────────────────────────
interface Loopback0
 description Router-ID
 ip address {loopback} 255.255.255.255
 ip ospf 1 area 0
 no shutdown
!
! ── LAN interface ───────────────────────────────────────────────────────────
interface GigabitEthernet0/0
 description {city}-LAN
 ip address {lan_net} 255.255.255.0
 ip ospf 1 area 1
 no shutdown
!
! ── WAN interface (OS2 SMF — transoceanic distances via DWDM/submarine) ─────
interface GigabitEthernet0/1
 description WAN-core-link OS2-SMF
 ip address 10.255.0.1 255.255.255.252
 ip ospf 1 area 0
 no shutdown
!
! ── IKEv2 / IPsec configuration ─────────────────────────────────────────────
crypto ikev2 proposal IKEV2-PROP
 encryption aes-cbc-256
 integrity sha256
 group 20
!
crypto ikev2 policy IKEV2-POL
 proposal IKEV2-PROP
!
crypto ikev2 keyring IKEV2-KEYRING
 peer WAN-PEERS
  address 0.0.0.0 0.0.0.0
  pre-shared-key local  NETARCH-SECRET-LOCAL
  pre-shared-key remote NETARCH-SECRET-REMOTE
!
crypto ikev2 profile IKEV2-PROFILE
 match address local interface GigabitEthernet0/1
 match identity remote address 0.0.0.0
 authentication remote pre-share
 authentication local  pre-share
 keyring local IKEV2-KEYRING
!
crypto ipsec transform-set TS-AES256-SHA256 esp-aes 256 esp-sha256-hmac
 mode tunnel
!
crypto ipsec profile IPSEC-PROFILE
 set transform-set TS-AES256-SHA256
 set ikev2-profile IKEV2-PROFILE
!
interface Tunnel0
 description IPsec-Tunnel-WAN
 tunnel source GigabitEthernet0/1
 tunnel mode ipsec ipv4
 tunnel protection ipsec profile IPSEC-PROFILE
 ip ospf 1 area 0
 no shutdown
!
! ── OSPF multi-area — wildcard masks in network statements ──────────────────
router ospf 1
 router-id {loopback}
 area 1 stub
 ! Summarise area 1 at the ABR
 area 1 range {lan_net} 255.255.255.0
 network {loopback} 0.0.0.0 area 0
 network {lan_net} 0.0.0.255 area 1
 network 10.255.0.0 0.0.0.3 area 0
!
! ── eBGP ─────────────────────────────────────────────────────────────────────
router bgp {asn}
 bgp router-id {loopback}
 bgp log-neighbor-changes
 no auto-summary
 no synchronization
{bgp_neighbor_stanzas}
 !
 address-family ipv4 unicast
  network {lan_net} mask 255.255.255.0
  ! Route summarisation — advertise aggregate only
  aggregate-address 10.0.0.0 255.0.0.0 summary-only
 exit-address-family
!
! ── Route-map for outbound policy ───────────────────────────────────────────
route-map RM-OUT-{city.upper()} permit 10
 match ip address prefix-list PL-{city.upper()}-LAN
 set local-preference 150
!
ip prefix-list PL-{city.upper()}-LAN seq 10 permit {lan_net}/24
!
end
"""


