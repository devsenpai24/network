def _generate_wan(topology: dict) -> Dict[str, str]:
    configs = {}

    nyc_bgp_neighbors = [
        ("10.200.0.1", 65002, "eBGP-to-LONDON-RTR01"),
        ("10.201.0.1", 65002, "eBGP-to-SINGAPORE-RTR01"),
        ("10.0.0.2",   65003, "eBGP-to-CLOUD-VPC-GW"),
    ]
    configs["NYC-RTR01"] = (
        _header("NYC-RTR01", "wan", "New York City site router")
        + _wan_site_router("NYC", 65001, "10.255.1.1", "10.10.1.0", nyc_bgp_neighbors)
    )

    lon_bgp_neighbors = [
        ("10.200.0.2", 65001, "eBGP-to-NYC-RTR01"),
        ("10.202.0.1", 65002, "eBGP-to-SINGAPORE-RTR01"),
    ]
    configs["LONDON-RTR01"] = (
        _header("LONDON-RTR01", "wan", "London site router")
        + _wan_site_router("LONDON", 65002, "10.255.2.1", "10.10.2.0", lon_bgp_neighbors)
    )

    sg_bgp_neighbors = [
        ("10.201.0.2", 65001, "eBGP-to-NYC-RTR01"),
        ("10.202.0.2", 65002, "eBGP-to-LONDON-RTR01"),
        ("10.203.0.1", 65002, "eBGP-to-SYDNEY-RTR01"),
    ]
    configs["SINGAPORE-RTR01"] = (
        _header("SINGAPORE-RTR01", "wan", "Singapore site router")
        + _wan_site_router("SINGAPORE", 65002, "10.255.3.1", "10.10.3.0", sg_bgp_neighbors)
    )

    syd_bgp_neighbors = [
        ("10.203.0.2", 65002, "eBGP-to-SINGAPORE-RTR01"),
    ]
    configs["SYDNEY-RTR01"] = (
        _header("SYDNEY-RTR01", "wan", "Sydney site router")
        + _wan_site_router("SYDNEY", 65002, "10.255.4.1", "10.10.4.0", syd_bgp_neighbors)
    )

    configs["CLOUD-VPC-GW"] = (
        _header("CLOUD-VPC-GW", "wan", "Cloud VPC gateway (50 m Cat6a direct connect)")
        + _wan_cloud_gw()
    )

    return configs


# ── Public API ─────────────────────────────────────────────────────────────────

def generate_configs(preset_name: str, topology: dict) -> Dict[str, str]:
    """
    Generate IOS-style device configurations for the named preset.

    Parameters
    ----------
    preset_name : str
        One of "campus", "metro", "wan".
    topology    : dict
        Optional overrides (currently unused; reserved for future custom-topology
        support).

    Returns
    -------
    dict mapping device_name → config_str.

    Raises
    ------
    ValueError
        For unknown preset names.
    """
    name = preset_name.lower().strip()
    if name == "campus":
        return _generate_campus(topology)
    elif name == "metro":
        return _generate_metro(topology)
    elif name == "wan":
        return _generate_wan(topology)
    else:
        raise ValueError(
            f"Unknown preset '{preset_name}'. Valid presets: campus, metro, wan."
        )
