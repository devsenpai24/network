"""
explain.py — Architectural decision logger for NetArchitect.

The ArchitecturalLog class collects Decision objects (from media.py / routing.py)
tagged with a category label, and renders them as plain text or Markdown.
"""
from dataclasses import dataclass, field
from typing import List


@dataclass
class _Entry:
    """Internal storage for a single logged decision."""
    category: str
    choice: str
    justification: str


class ArchitecturalLog:
    """
    Collect and render architectural decisions made by NetArchitect.

    Usage
    -----
    ::

        log = ArchitecturalLog()
        log.add("Media Selection", media_decision)
        log.add("Routing Protocol", routing_decision)

        print(log.render_text())
        with open("rationale.md", "w") as f:
            f.write(log.render_markdown())
    """

    def __init__(self):
        self._entries: List[_Entry] = []

    # ── Public API ────────────────────────────────────────────────────────────

    def add(self, category: str, decision) -> None:
        """
        Store a decision under *category*.

        Parameters
        ----------
        category : str
            Human-readable label (e.g. "Media: building-a-to-core").
        decision : Decision namedtuple
            Any object with .choice and .justification attributes.
        """
        self._entries.append(
            _Entry(
                category=category,
                choice=decision.choice,
                justification=decision.justification,
            )
        )

    def render_text(self) -> str:
        """Return a plain-text formatted Architectural Rationale Log."""
        separator = "=" * 72
        lines = [
            separator,
            "  ARCHITECTURAL RATIONALE LOG — NetArchitect",
            separator,
            "",
        ]
        for i, entry in enumerate(self._entries, start=1):
            lines.append(f"[{i}] Category    : {entry.category}")
            lines.append(f"    Choice      : {entry.choice}")
            lines.append(f"    Justification:")
            # Word-wrap at 68 chars with 6-space indent
            words = entry.justification.split()
            current_line = "      "
            for word in words:
                if len(current_line) + len(word) + 1 > 74:
                    lines.append(current_line)
                    current_line = "      " + word
                else:
                    if current_line == "      ":
                        current_line += word
                    else:
                        current_line += " " + word
            if current_line.strip():
                lines.append(current_line)
            lines.append("")

        lines.append(separator)
        return "\n".join(lines)

    def render_markdown(self) -> str:
        """Return a Markdown-formatted Architectural Rationale Log."""
        lines = [
            "# Architectural Rationale Log",
            "",
            "_Generated by NetArchitect_",
            "",
        ]
        for i, entry in enumerate(self._entries, start=1):
            lines.append(f"## {i}. {entry.category}")
            lines.append("")
            lines.append(f"**Choice:** `{entry.choice}`")
            lines.append("")
            lines.append(f"**Justification:** {entry.justification}")
            lines.append("")
            lines.append("---")
            lines.append("")

        return "\n".join(lines)

    def __len__(self) -> int:
        return len(self._entries)

    def __repr__(self) -> str:
        return f"ArchitecturalLog({len(self._entries)} entries)"
